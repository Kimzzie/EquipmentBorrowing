using System.Net;
using System.Text.Json;
using EquipmentBorrowing.Api.Contracts;
using EquipmentBorrowing.Tests.Infrastructure;

namespace EquipmentBorrowing.Tests.UseCases;

/// <summary>TC6-U12 Register student (API-03, API-04) and TC6-U13 Update student (API-02, 03, 05, 15).</summary>
[Collection("Api")]
public sealed class StudentManagementTests : ApiTestBase
{
    public StudentManagementTests(ApiFactory factory) : base(factory) { }

    // ---------------- TC6-U12 ----------------

    [Fact, Trait("TC6", "U12")]
    public async Task U12_Register_student_returns_201_with_Location_default_eligibility_and_a_durable_row()
    {
        var response = await RegisterStudentAsync("ST-500", "Eli Tan", contact: null);
        var body = await response.Content.ReadAsStringAsync();

        Assert.Equal(HttpStatusCode.Created, response.StatusCode);

        // Contract check on the raw JSON.
        using (var doc = JsonDocument.Parse(body))
            foreach (var name in new[] { "id", "studentNumber", "fullName", "contact", "isEligible" })
                Assert.True(doc.RootElement.TryGetProperty(name, out _), $"JSON property '{name}' is missing.");

        var created = JsonSerializer.Deserialize<StudentDto>(body, Json)!;

        Assert.True(created.Id > 0);                 // generated by the server, never supplied by the client
        Assert.Equal("ST-500", created.StudentNumber);
        Assert.Equal("Eli Tan", created.FullName);
        Assert.Null(created.Contact);                // omitted optional field = absent
        Assert.True(created.IsEligible);             // BR-02: new students are eligible

        // Location header points at API-03 and returns the same student.
        var location = response.Headers.Location;
        Assert.NotNull(location);
        Assert.EndsWith($"/api/v1/students/{created.Id}", location!.ToString());

        var fetched = await Client.GetAsync(location);
        Assert.Equal(HttpStatusCode.OK, fetched.StatusCode);
        Assert.Equal(created, await ReadAsync<StudentDto>(fetched));

        // Fresh PostgreSQL connection: exactly one new durable row with the right defaults.
        Assert.Equal(5, await TestDatabase.CountAsync("Students"));
        Assert.Equal(1, await TestDatabase.ScalarAsync<long>(
            "SELECT COUNT(*) FROM \"Students\" WHERE \"StudentNumber\" = 'ST-500'"));
        Assert.True(await TestDatabase.IsAllowedToBorrowAsync(created.Id));
        Assert.Equal(1, await TestDatabase.ScalarAsync<long>(
            "SELECT COUNT(*) FROM \"Students\" WHERE \"Id\" = @id AND \"Contact\" IS NULL", ("id", created.Id)));
        Assert.Equal(0, await TestDatabase.BorrowingCountForStudentAsync(created.Id));
    }

    [Fact, Trait("TC6", "U12")]
    public async Task U12_Register_student_stores_the_optional_contact_when_it_is_supplied()
    {
        var response = await RegisterStudentAsync("ST-501", "Fay Uy", contact: "0917-123-4567");

        Assert.Equal(HttpStatusCode.Created, response.StatusCode);
        var created = await ReadAsync<StudentDto>(response);
        Assert.Equal("0917-123-4567", created.Contact);

        Assert.Equal("0917-123-4567", await TestDatabase.ScalarAsync<string>(
            "SELECT \"Contact\" FROM \"Students\" WHERE \"Id\" = @id", ("id", created.Id)));
    }

    // ---------------- TC6-U13 ----------------

    [Fact, Trait("TC6", "U13")]
    public async Task U13_Search_finds_S1_by_number_and_returns_an_empty_array_for_no_match()
    {
        var found = await Client.GetAsync("/api/v1/students?search=ST-100");
        Assert.Equal(HttpStatusCode.OK, found.StatusCode);
        var students = await ReadAsync<List<StudentDto>>(found);
        var only = Assert.Single(students);
        Assert.Equal("ST-100", only.StudentNumber);
        Assert.Equal("Ada Cruz", only.FullName);

        var none = await Client.GetAsync("/api/v1/students?search=no-such-student");
        Assert.Equal(HttpStatusCode.OK, none.StatusCode);                 // no match is NOT an error
        Assert.Equal("[]", (await none.Content.ReadAsStringAsync()).Trim());
    }

    [Fact, Trait("TC6", "U13")]
    public async Task U13_Update_changes_the_fields_but_keeps_identity_and_borrowing_history()
    {
        var s1 = await StudentIdAsync("ST-100");
        var historyBefore = await ReadAsync<List<BorrowingDto>>(
            await Client.GetAsync($"/api/v1/students/{s1}/borrowings"));
        Assert.Equal(2, historyBefore.Count);

        var update = await UpdateStudentAsync(s1, "ST-100", "Ada Cruz-Reyes", "0917-555-0100");

        Assert.Equal(HttpStatusCode.OK, update.StatusCode);
        var updated = await ReadAsync<StudentDto>(update);
        Assert.Equal(s1, updated.Id);                                     // stable identity
        Assert.Equal("ST-100", updated.StudentNumber);
        Assert.Equal("Ada Cruz-Reyes", updated.FullName);
        Assert.Equal("0917-555-0100", updated.Contact);
        Assert.True(updated.IsEligible);                                  // eligibility is not an edit field

        // GET returns the edited student (API-03).
        var fetched = await ReadAsync<StudentDto>(await Client.GetAsync($"/api/v1/students/{s1}"));
        Assert.Equal(updated, fetched);

        // History (API-15): same two borrowings, same ids, same statuses and dates; only the joined name changed.
        var historyAfter = await ReadAsync<List<BorrowingDto>>(
            await Client.GetAsync($"/api/v1/students/{s1}/borrowings"));
        Assert.Equal(
            historyBefore.OrderBy(b => b.Id).Select(b => (b.Id, b.EquipmentId, b.Status, b.BorrowedDate, b.ReturnedDate)),
            historyAfter.OrderBy(b => b.Id).Select(b => (b.Id, b.EquipmentId, b.Status, b.BorrowedDate, b.ReturnedDate)));
        Assert.All(historyAfter, b => Assert.Equal(s1, b.StudentId));
        Assert.All(historyAfter, b => Assert.Equal("Ada Cruz-Reyes", b.StudentName));

        // Fresh PostgreSQL connection: same row edited in place, foreign keys intact, nothing added or lost.
        Assert.Equal("Ada Cruz-Reyes", await TestDatabase.ScalarAsync<string>(
            "SELECT \"Name\" FROM \"Students\" WHERE \"Id\" = @id", ("id", s1)));
        Assert.Equal("0917-555-0100", await TestDatabase.ScalarAsync<string>(
            "SELECT \"Contact\" FROM \"Students\" WHERE \"Id\" = @id", ("id", s1)));
        Assert.Equal(4, await TestDatabase.CountAsync("Students"));
        Assert.Equal(2, await TestDatabase.BorrowingCountForStudentAsync(s1));
        Assert.Equal(4, await TestDatabase.CountAsync("Borrowings"));
        Assert.Equal(0, await TestDatabase.ConsistencyViolationsAsync());
    }
}
